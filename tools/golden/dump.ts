/*
 * Regenerates the two contracts for the Rust port:
 *
 *   src-tauri/tests/engine-golden.json   replay scripts + the exact frame the
 *                                        TypeScript engine produces for them
 *   src-tauri/assets/engine-catalogue.json  static data (profiles, shapes,
 *                                        expressions, orbits, the eyefit table)
 *
 * The Rust engine is correct when it replays every script and matches the frame.
 * The catalogue is dumped rather than retyped so values that were measured or
 * solved once (notably the `eyefit` table) cannot drift by transcription.
 *
 *   pnpm exec vitest run --config vitest.golden.config.ts
 */
