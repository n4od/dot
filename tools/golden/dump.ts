import { SURFACE_RULES } from '../../src/pet/materials'

interface Init {
  state: StateId
  shape?: string
  expr?: string
}

type Op =
  | { kind: 'state'; id: StateId; at: number }
  | { kind: 'shape'; shape: string | null; at: number }
  | { kind: 'expr'; expr: string | null; at: number }
  | { kind: 'look'; look: Look | null; at: number; morph?: number }

interface GoldenCase {
  name: string
  init: Init
  ops: Op[]
  t: number
  frame: BotFrame
}

const here = fileURLToPath(new URL('.', import.meta.url))
const root = resolve(here, '../..')
const goldenFile = resolve(root, 'src-tauri/tests/engine-golden.json')
const catalogueFile = resolve(root, 'src-tauri/assets/engine-catalogue.json')

function makeEngine(init: Init): BotEngine {
  const shape = init.shape ? SHAPE_BY_ID.get(init.shape)!.radii : null
  const expr = init.expr ? EXPRESSION_BY_ID.get(init.expr)! : null
  const engine = new BotEngine(RAYON, init.state, shape, expr)
  engine.reset(init.state, 0)
  return engine
}

function apply(engine: BotEngine, op: Op) {
  if (op.kind === 'state') engine.setState(op.id, op.at)
  else if (op.kind === 'shape') engine.setShape(op.shape ? SHAPE_BY_ID.get(op.shape)!.radii : null, op.at)
  else if (op.kind === 'expr') engine.setExpression(op.expr ? EXPRESSION_BY_ID.get(op.expr)! : null, op.at)
  else engine.setLook(op.look, op.at, op.morph ?? BotEngine.LOOK_MORPH)
}

