/* ---------------------------------------------------------------- the cases */

const cases: GoldenCase[] = []

function emit(name: string, init: Init, ops: Op[], times: number[]) {
  const engine = makeEngine(init)
  for (const op of ops) apply(engine, op)
  for (const t of times) cases.push({ name: `${name}@${t}`, init, ops, t, frame: engine.sample(t) })
}

it('regenerates the golden frames and the catalogue', () => {
  // Every state across its own duration.
  for (const def of STATES) {
    emit(`state:${def.id}`, { state: def.id }, [], [0, 0.05, 0.2, 0.5, 1.0, def.duration * 0.9])
  }

  // A plain transition, and a second change while one is still morphing.
  emit('trans:idle->wide', { state: 'idle' }, [{ kind: 'state', id: 'wide', at: 0.5 }], [0.5, 0.55, 0.7, 0.9, 1.1])
  emit(
    'trans:chain',
    { state: 'idle' },
    [
      { kind: 'state', id: 'orbit', at: 0.2 },
      { kind: 'state', id: 'burst', at: 0.9 }
    ],
    [0.9, 1.0, 1.2, 1.6]
  )

  // Gaze targets, including a spin and a nonzero wander.
  emit(
    'look:a',
    { state: 'idle' },
    [{ kind: 'look', look: { yaw: 30, pitch: 10, mix: 1, spin: 0, wander: 0 }, at: 0 }],
    [0, 0.05, 0.12, 0.24, 1.0]
  )
  emit(
    'look:b',
    { state: 'idle' },
    [{ kind: 'look', look: { yaw: -18, pitch: -13, mix: 1, spin: 180, wander: 0.3 }, at: 0 }],
    [0, 0.1, 0.3]
  )

  // Every catalogue shape at rest, and one shape morph travelling.
  for (const shape of SHAPES) emit(`shape:${shape.id}`, { state: 'idle', shape: shape.id }, [], [0.7])
  emit(
    'shapeMorph',
    { state: 'idle', shape: SHAPES[0]!.id },
    [{ kind: 'shape', shape: SHAPES[3]!.id, at: 0.4 }],
    [0.4, 0.5, 0.7, 0.9]
  )

  // Every expression at rest, and one expression morph travelling.
  for (const expr of EXPRESSIONS) emit(`expr:${expr.id}`, { state: 'idle', expr: expr.id }, [], [0.7])
  emit(
    'exprMorph',
    { state: 'idle', expr: EXPRESSIONS[0]!.id },
    [{ kind: 'expr', expr: EXPRESSIONS[5]!.id, at: 0.3 }],
    [0.3, 0.4, 0.6, 0.8]
  )

  // Everything at once.
  emit(
    'combined',
    { state: 'idle', shape: SHAPES[6]!.id, expr: EXPRESSIONS[8]!.id },
    [{ kind: 'look', look: { yaw: 20, pitch: -10, mix: 1, spin: 0, wander: 0 }, at: 0 }],
    [0, 0.12, 0.5]
  )

  expect(cases.length).toBeGreaterThan(80)

  mkdirSync(dirname(goldenFile), { recursive: true })
  mkdirSync(dirname(catalogueFile), { recursive: true })
  writeFileSync(goldenFile, JSON.stringify({ count: cases.length, scale: RAYON, cases }, null, 2) + '\n')
  writeFileSync(catalogueFile, JSON.stringify(catalogue, null, 2) + '\n')
  // eslint-disable-next-line no-console
  console.log(`wrote ${cases.length} cases -> ${goldenFile}`)
  // eslint-disable-next-line no-console
  console.log(`wrote catalogue -> ${catalogueFile}`)
})