import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { expect, it } from 'vitest'

import { COMET_RIBBONS, DOT_PEAK, DOT_R, DOT_X, NOTIF_ANGLE, NOTIF_BLUE, NOTIF_DIST, NOTIF_MARGIN, NOTIF_POP, NOTIF_R, RINGS, SWOOSH, COMET_DOT } from '../../src/bot/decor'
import { BotEngine, type BotFrame, type Look } from '../../src/bot/engine'
import { decalageDesYeux } from '../../src/bot/eyefit'
import { EXPRESSION_BY_ID, EXPRESSIONS } from '../../src/bot/expressions'
