/** Replayed from `decor.ts`, whose constants are private. */
const P_RNG = createRng(0xbeef)
const particles = Array.from({ length: 5 }, (_, i) => ({
  birth: i * 0.2,
  angle: P_RNG() * TAU,
  rho: 0.58 + P_RNG() * 0.18
}))

/** Replayed from `face.ts`, whose schedule is private. */
const BLINK_RNG = createRng(0x5eed)
const blinks: number[] = []
{
  let t = 1.4
  while (t < 900) {
    blinks.push(t)
    t += 1.9 + BLINK_RNG() * 2.7
    if (BLINK_RNG() < 0.18) {
      blinks.push(t)
      t += 0.24
    }
  }
}

/** Replayed from `states.ts`, whose glyph constants are private. */
const BAR_UPRIGHT_CY = -0.1875
const barUpright = profileFromPolygon(hullOfCircles(0, -0.505, 0.132, 0, 0.13, 0.075), 0, BAR_UPRIGHT_CY)
const barItalic = profileFromPolygon(hullOfCircles(0, -0.2535, 0.1345, 0, 0.2535, 0.1345), 0, 0)
const tear = polyPath(hullOfCircles(0, 0, 0.118, 0, 0.172, 0.012))
/** `play` spins about this radius; read it back from the pose itself. */
const triOrbit = STATE_BY_ID.get('play')!.pose(0).sil.cy

function decalages(): Record<string, Record<string, { x: number; y: number }>> {
  const out: Record<string, Record<string, { x: number; y: number }>> = {}
  for (const shape of SHAPES) {
    const byKey: Record<string, { x: number; y: number }> = {}
    for (const def of STATES) {
      if (!def.baseBody) continue
      const exprs = def.baseFace ? [null, ...EXPRESSIONS] : [null]
      for (const expr of exprs) {
        byKey[`${def.id}|${expr?.id ?? ''}`] = decalageDesYeux(shape.radii, def.id, expr?.id ?? null)
      }
    }
    out[shape.id] = byKey
  }
  return out
}

